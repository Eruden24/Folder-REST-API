package com.eruden.foldersdemo.folder;

import com.eruden.foldersdemo.common.exception.ConflictException;
import com.eruden.foldersdemo.folder.dto.CreateFolderRequest;
import com.eruden.foldersdemo.folder.dto.FolderResponse;
import com.eruden.foldersdemo.folder.dto.UpdateFolderRequest;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/**
 * Unit tests: no Spring, no database. The repository is a Mockito mock, so these run in milliseconds
 * and test only the business rules in FolderService.
 */
@ExtendWith(MockitoExtension.class)
class FolderServiceTest {

    @Mock
    private FolderRepository folderRepository;

    @InjectMocks
    private FolderService folderService;

    @Test
    void create_withoutParent_savesRootFolder() {
        when(folderRepository.save(any(Folder.class))).thenAnswer(invocation -> {
            Folder saved = invocation.getArgument(0);
            ReflectionTestUtils.setField(saved, "id", 1L);
            return saved;
        });

        FolderResponse response = folderService.create(new CreateFolderRequest("Documents", null));

        assertThat(response.id()).isEqualTo(1L);
        assertThat(response.subject()).isEqualTo("Documents");
        assertThat(response.parentId()).isNull();
    }

    @Test
    void create_withMissingParent_throwsNotFoundAndSavesNothing() {
        when(folderRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> folderService.create(new CreateFolderRequest("Documents", 99L)))
                .isInstanceOf(FolderNotFoundException.class)
                .hasMessageContaining("99");
        verify(folderRepository, never()).save(any());
    }

    @Test
    void getById_withMissingFolder_throwsNotFound() {
        when(folderRepository.findById(1L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> folderService.getById(1L))
                .isInstanceOf(FolderNotFoundException.class);
    }

    @Test
    void update_renamesAndMovesFolder() {
        Folder folder = folder(1L, "Old name", null);
        Folder newParent = folder(2L, "Parent", null);
        when(folderRepository.findById(1L)).thenReturn(Optional.of(folder));
        when(folderRepository.findById(2L)).thenReturn(Optional.of(newParent));

        FolderResponse response = folderService.update(1L, new UpdateFolderRequest("New name", 2L));

        assertThat(response.subject()).isEqualTo("New name");
        assertThat(response.parentId()).isEqualTo(2L);
    }

    @Test
    void update_movingFolderIntoItself_throwsConflict() {
        Folder folder = folder(1L, "A", null);
        when(folderRepository.findById(1L)).thenReturn(Optional.of(folder));

        assertThatThrownBy(() -> folderService.update(1L, new UpdateFolderRequest("A", 1L)))
                .isInstanceOf(ConflictException.class);
    }

    @Test
    void update_movingFolderIntoItsOwnGrandchild_throwsConflict() {
        // A -> B -> C ; moving A under C would create a cycle
        Folder a = folder(1L, "A", null);
        Folder b = folder(2L, "B", a);
        Folder c = folder(3L, "C", b);
        when(folderRepository.findById(1L)).thenReturn(Optional.of(a));
        when(folderRepository.findById(3L)).thenReturn(Optional.of(c));

        assertThatThrownBy(() -> folderService.update(1L, new UpdateFolderRequest("A", 3L)))
                .isInstanceOf(ConflictException.class);
        assertThat(a.getParent()).isNull();
    }

    @Test
    void delete_folderWithSubfolders_throwsConflict() {
        when(folderRepository.findById(1L)).thenReturn(Optional.of(folder(1L, "A", null)));
        when(folderRepository.existsByParentId(1L)).thenReturn(true);

        assertThatThrownBy(() -> folderService.delete(1L))
                .isInstanceOf(ConflictException.class);
        verify(folderRepository, never()).delete(any());
    }

    @Test
    void delete_emptyFolder_deletesIt() {
        Folder folder = folder(1L, "A", null);
        when(folderRepository.findById(1L)).thenReturn(Optional.of(folder));
        when(folderRepository.existsByParentId(1L)).thenReturn(false);

        folderService.delete(1L);

        verify(folderRepository).delete(folder);
    }

    // The id is normally generated by the database, so tests set it directly.
    private static Folder folder(Long id, String subject, Folder parent) {
        Folder folder = new Folder(subject, parent);
        ReflectionTestUtils.setField(folder, "id", id);
        return folder;
    }
}
